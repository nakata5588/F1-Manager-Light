// scripts/build-historical-assets.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"..");
const outputPath=path.join(root,"src/generated/historicalAssets.js");

const SOURCES={
  drivers:[
    {dir:"public/assets/drivers",priority:0},
    {dir:"public/portraits/drivers",priority:10},
  ],
  staff:[
    {dir:"public/assets/staff",priority:0},
    {dir:"public/portraits/staff",priority:10},
  ],
  teams:[
    {dir:"public/assets/teams",priority:0},
    {dir:"public/logos/teams",priority:10},
  ],
};

const IMAGE_EXTENSIONS=new Set([".webp",".png",".jpg",".jpeg",".svg"]);

function normalizeAlias(value){
  return String(value??"").trim().toLowerCase().replace(/[^a-z0-9]+/g,"");
}

function parseAssetFile(fileName){
  const ext=path.extname(fileName).toLowerCase();
  if(!IMAGE_EXTENSIONS.has(ext))return null;
  const stem=fileName.slice(0,-ext.length);
  const historical=stem.match(/^(.*)_(19\d{2}|20\d{2}|21\d{2})$/);
  const rawAlias=historical?historical[1]:stem;
  const alias=normalizeAlias(rawAlias);
  if(!alias)return null;
  return {
    alias,
    year:historical?Number(historical[2]):null,
  };
}

function publicPath(relativePath){
  return "/"+String(relativePath).replaceAll("\\","/").replace(/^public\//,"");
}

function candidateWins(next,current){
  if(!current)return true;
  if(next.priority!==current.priority)return next.priority<current.priority;
  return next.path.localeCompare(current.path)<0;
}

const working={drivers:new Map(),staff:new Map(),teams:new Map()};

for(const [type,sources] of Object.entries(SOURCES)){
  for(const source of sources){
    const absoluteDir=path.join(root,source.dir);
    if(!fs.existsSync(absoluteDir))continue;
    for(const entry of fs.readdirSync(absoluteDir,{withFileTypes:true})){
      if(!entry.isFile())continue;
      const parsed=parseAssetFile(entry.name);
      if(!parsed)continue;
      const key=parsed.alias;
      const record=working[type].get(key)||{default:null,history:new Map()};
      const candidate={
        path:publicPath(path.posix.join(source.dir,entry.name)),
        priority:source.priority,
      };
      if(parsed.year==null){
        if(candidateWins(candidate,record.default))record.default=candidate;
      }else{
        const current=record.history.get(parsed.year);
        if(candidateWins(candidate,current))record.history.set(parsed.year,candidate);
      }
      working[type].set(key,record);
    }
  }
}

const manifest={drivers:{},staff:{},teams:{}};
for(const type of Object.keys(manifest)){
  for(const [key,record] of [...working[type].entries()].sort(([a],[b])=>a.localeCompare(b))){
    manifest[type][key]={
      default:record.default?.path||"",
      history:[...record.history.entries()]
        .sort(([a],[b])=>a-b)
        .map(([year,candidate])=>({year,path:candidate.path})),
    };
  }
}

fs.mkdirSync(path.dirname(outputPath),{recursive:true});
const body=`// AUTO-GENERATED by scripts/build-historical-assets.mjs. Do not edit by hand.\n`+
  `export const HISTORICAL_ASSET_MANIFEST = ${JSON.stringify(manifest,null,2)};\n`+
  `export default HISTORICAL_ASSET_MANIFEST;\n`;
fs.writeFileSync(outputPath,body,"utf8");

const counts=Object.fromEntries(
  Object.entries(manifest).map(([type,records])=>[
    type,
    Object.values(records).reduce((sum,row)=>sum+Number(Boolean(row.default))+row.history.length,0),
  ])
);
console.log("[historical-assets] generated",counts);
